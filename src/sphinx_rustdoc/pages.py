"""Write the generated pages: one per module and per type, each naming the parts the directives render."""

from __future__ import annotations

from pathlib import Path

from .domain import SECTIONS, MembersDirective, documented_here, reexports
from .model import PAGE_PREFIX, Crate, kind_of


def docname(crate: Crate, item_id: int) -> str:
    """The page's path under the output folder, without a suffix, as on docs.rs."""
    path = crate.canonical[item_id]
    kind = kind_of(crate.index[str(item_id)])
    if kind == "module":
        return "/".join(path) + "/index"
    return "/".join(path[:-1]) + f"/{PAGE_PREFIX[kind]}.{path[-1]}"


def _directive(name: str, *arguments: str) -> list[str]:
    return [f"```{{rust:{name}}} {' '.join(arguments)}", "```", ""]


def module_page(crate: Crate, module_id: int, stamp: str) -> str:
    ref = f"{crate.name}:{module_id}"
    path = crate.canonical[module_id]
    lines = [stamp, "", f"# {path[-1]}", "", *_directive("item", ref)]
    children: list[str] = []
    for kind, heading, style in SECTIONS:
        ids = documented_here(crate, module_id, kind)
        if not ids:
            continue
        lines += [f"## {heading}", ""]
        if style == "list":
            lines += _directive("summary", ref, kind)
        else:
            for item_id in ids:
                lines += _directive("item", f"{crate.name}:{item_id}")
        if kind == "module" or kind in PAGE_PREFIX:
            here = "/".join(path)
            children += [docname(crate, i).removeprefix(f"{here}/") for i in ids]
    if reexports(crate, module_id):
        lines += ["## Re-exports", "", *_directive("reexports", ref)]
    if children:
        lines += ["```{toctree}", ":hidden:", "", *children, "```", ""]
    return "\n".join(lines)


def type_page(crate: Crate, item_id: int, stamp: str) -> str:
    ref = f"{crate.name}:{item_id}"
    item = crate.index[str(item_id)]
    kind = kind_of(item)
    lines = [stamp, "", f"# {crate.canonical[item_id][-1]}", "", *_directive("item", ref)]
    if kind in ("struct", "union") and crate.fields(item_id):
        lines += ["## Fields", "", *_directive("members", ref, "fields")]
    if kind == "enum" and item["inner"]["enum"]["variants"]:
        lines += ["## Variants", "", *_directive("members", ref, "variants")]
    if kind == "trait":
        for group, heading in (("required", "Required items"), ("provided", "Provided items")):
            if MembersDirective.trait_items(crate, item, group):
                lines += [f"## {heading}", "", *_directive("members", ref, group)]
        if any(crate.item(i) is not None for i in item["inner"]["trait"]["implementations"]):
            lines += ["## Implementors", "", *_directive("members", ref, "implementors")]
    if kind in ("struct", "union", "enum"):
        impls = crate.impls(item_id)
        if impls.inherent:
            lines += ["## Implementations", "", *_directive("members", ref, "methods")]
        if impls.traits or impls.derived or impls.auto:
            lines += ["## Trait implementations", "", *_directive("members", ref, "traits")]
    return "\n".join(lines)


def write(crate: Crate, folder: Path, json_hash: str) -> list[Path]:
    """Write the crate's pages under `folder`, rewriting only pages that changed. Returns every page."""
    # The stamp changes with the JSON, so Sphinx rereads every page when the crate changes.
    version = f" {crate.version}" if crate.version else ""
    stamp = (
        f"% Generated by sphinx-rustdoc from {crate.name}{version}'s rustdoc JSON ({json_hash}). "
        "Rebuild the docs rather than editing it."
    )
    pages: dict[Path, str] = {}
    for item_id in crate.canonical:
        kind = kind_of(crate.index[str(item_id)])
        if kind == "module":
            pages[folder / f"{docname(crate, item_id)}.md"] = module_page(crate, item_id, stamp)
        elif kind in PAGE_PREFIX:
            pages[folder / f"{docname(crate, item_id)}.md"] = type_page(crate, item_id, stamp)
    for page, text in pages.items():
        page.parent.mkdir(parents=True, exist_ok=True)
        if not page.exists() or page.read_text(encoding="utf-8") != text:
            page.write_text(text, encoding="utf-8")
    return list(pages)


def remove_stale(folder: Path, written: set[Path]) -> None:
    """Delete pages under `folder` that this build didn't write, such as a removed crate's."""
    for page in folder.rglob("*.md"):
        if page not in written:
            page.unlink()
